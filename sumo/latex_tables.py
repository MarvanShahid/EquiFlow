"""latex_tables.py - LaTeX tables for the report, generated from the CSV results (no hand-copied numbers).

    python latex_tables.py        # -> ../docs/latex/results_tables.tex  (\\input it from the chapter)

Sources: results/heldout/{summary_stats,paired,marl_heldout}.csv (aggregate.py), results/performance.csv
(benchmark.py), ../Projects/tracking_out/tracking_scores.csv (score_tracking.py).
"""
from __future__ import annotations

import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent
RES = ROOT / "results" / "heldout"
OUT = ROOT.parent / "docs" / "latex" / "results_tables.tex"
NAMES = {"fixed": "Fixed-time", "actuated": "Actuated", "fixed+preempt": "Fixed + priority",
         "equiflow": "EquiFlow", "equiflow-marl": "EquiFlow (MARL)", "equiflow-norecovery": "No recovery",
         "equiflow-nogapout": "No gap-out", "equiflow-nocorridor": "No corridor",
         "equiflow-recovery-v1": "Old recovery rule"}
LABELS = {"car_wait_s": "Car mean wait (s)", "mean_wait_s": "Ordinary vehicles, mean wait (s)",
          "p95_wait_s": "95th-percentile wait (s)", "max_wait_s": "Longest single wait (s)",
          "share_wait_over_60s": "Share waiting $>$60 s", "worst_approach_mean_wait_s": "Worst approach, mean wait (s)",
          "jain_approach_wait": "Jain index across approaches", "ambulance_wait_s": "Ambulance mean wait (s)",
          "ambulance_travel_s": "Ambulance travel time (s)", "detection_to_green_s": "Detection to green (s)",
          "recovery_s_mean": "Recovery interval (s)"}


def esc(s: str) -> str:
    return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("#", r"\#")


def load_stats():
    S = {}
    for r in csv.DictReader((RES / "summary_stats.csv").open()):
        m = float(r["mean"]) if r["mean"] else None
        ci = float(r["ci95"]) if r["ci95"] not in ("", "nan") else None
        S[(r["controller"], r["metric"])] = (m, ci, int(r["n"]))
    return S


def cell(v, digits=2, ci=True):
    m, c, _ = v
    if m is None:
        return "--"
    return f"{m:.{digits}f}" + (f" $\\pm$ {c:.{digits}f}" if ci and c is not None else "")


def table(caption, label, ctrls, metrics, S, size=r"\small"):
    cols = "l" + "c" * len(ctrls)
    L = [r"\begin{table}[htbp]", r"\centering", size, rf"\caption{{{caption}}}", rf"\label{{{label}}}",
         r"\resizebox{\textwidth}{!}{%", rf"\begin{{tabular}}{{{cols}}}", r"\hline",
         "Metric & " + " & ".join(NAMES.get(c, esc(c)) for c in ctrls) + r" \\", r"\hline"]
    for m in metrics:
        d = 3 if m in ("jain_approach_wait", "share_wait_over_60s") else 2
        L.append(f"{LABELS[m]} & " + " & ".join(cell(S.get((c, m), (None, None, 0)), d) for c in ctrls) + r" \\")
    L.append("Runs & " + " & ".join(str(S.get((c, "car_wait_s"), (0, 0, 0))[2]) for c in ctrls) + r" \\")
    L += [r"\hline", r"\end{tabular}}", r"\end{table}", ""]
    return L


def main():
    S = load_stats()
    ctrls = {c for c, _ in S}
    main_c = [c for c in ("fixed", "actuated", "fixed+preempt", "equiflow", "equiflow-marl") if c in ctrls]
    abl_c = [c for c in ("equiflow", "equiflow-recovery-v1", "equiflow-norecovery", "equiflow-nogapout",
                         "equiflow-nocorridor") if c in ctrls]
    L = ["% Generated by sumo/latex_tables.py from the CSV results. Do not edit by hand; re-run the script.", ""]
    L += table("Held-out evaluation: mean $\\pm$ 95\\% confidence interval over one-hour SUMO runs (seeds 6--10).",
               "tab:it2-main", main_c, list(LABELS), S)
    L += table("Ablations: EquiFlow with one component switched off (the corridor ablation runs only on the two "
               "multi-junction networks).", "tab:it2-ablation", abl_c,
               ["car_wait_s", "p95_wait_s", "max_wait_s", "jain_approach_wait", "ambulance_wait_s",
                "ambulance_travel_s", "recovery_s_mean"], S)

    # paired
    pf = RES / "paired.csv"
    if pf.exists():
        rows = [r for r in csv.DictReader(pf.open())
                if r["metric"] in ("car_wait_s", "p95_wait_s", "max_wait_s", "ambulance_wait_s")
                and r["versus"] != "equiflow-nocorridor"]
        L += [r"\begin{table}[htbp]", r"\centering", r"\small",
              r"\caption{Paired comparison on identical runs (same network, demand and seed): EquiFlow minus the "
              r"other controller. Negative values mean EquiFlow is lower. $^*$: the 95\% CI excludes zero.}",
              r"\label{tab:it2-paired}", r"\begin{tabular}{llccc}", r"\hline",
              r"Versus & Metric & Difference (95\% CI) & EquiFlow better in & Runs \\", r"\hline"]
        for r in rows:
            m, ci = float(r["mean_diff"]), r["ci95"]
            ci = f" $\\pm$ {float(ci):.2f}" if ci not in ("", "nan") else ""
            star = "$^*$" if r["significant"] == "True" else ""
            L.append(f"{NAMES.get(r['versus'], esc(r['versus']))} & {LABELS[r['metric']]} & {m:+.2f}{ci}{star} & "
                     f"{100 * float(r['ref_wins_share']):.0f}\\% & {r['n']} \\\\")
        L += [r"\hline", r"\end{tabular}", r"\end{table}", ""]

    # marl held out
    mf = RES / "marl_heldout.csv"
    if mf.exists():
        M = {(r["network_demand_in_training"], r["metric"]): r for r in csv.DictReader(mf.open())}
        L += [r"\begin{table}[htbp]", r"\centering", r"\small",
              r"\caption{MARL minus adaptive EquiFlow on identical runs, split by whether the network/demand "
              r"combination was used in MARL training. All seeds are unseen. Negative = MARL lower.}",
              r"\label{tab:it2-marl}", r"\begin{tabular}{lcc}", r"\hline",
              r"Metric & Trained combinations & Unseen combinations \\", r"\hline"]
        for m in ("car_wait_s", "p95_wait_s", "jain_approach_wait", "ambulance_wait_s"):
            cells = []
            for seen in ("True", "False"):
                r = M.get((seen, m))
                if not r or not r["n"] or r["n"] == "0":
                    cells.append("--")
                    continue
                d = 3 if m == "jain_approach_wait" else 2
                ci = f" $\\pm$ {float(r['ci95']):.{d}f}" if r["ci95"] not in ("", "nan") else ""
                cells.append(f"{float(r['marl_minus_adaptive']):+.{d}f}{ci} (n={r['n']})")
            L.append(f"{LABELS[m]} & " + " & ".join(cells) + r" \\")
        L += [r"\hline", r"\end{tabular}", r"\end{table}", ""]

    # performance
    pf = ROOT / "results" / "performance.csv"
    if pf.exists():
        L += [r"\begin{table}[htbp]", r"\centering", r"\small",
              r"\caption{Signal controller timing on one CPU core (sumo/benchmark.py). The live backend ticks every "
              r"100\,000\,$\mu$s.}", r"\label{tab:it2-perf}", r"\begin{tabular}{lcccc}", r"\hline",
              r"Measured & Mean ($\mu$s) & Median & p99 & Max \\", r"\hline"]
        for r in csv.DictReader(pf.open()):
            L.append(f"{esc(r['what'])} & {r['mean_us']} & {r['median_us']} & {r['p99_us']} & {r['max_us']} \\\\")
        L += [r"\hline", r"\end{tabular}", r"\end{table}", ""]

    # tracking
    tf = ROOT.parent / "Projects" / "tracking_out" / "tracking_scores.csv"
    if tf.exists():
        L += [r"\begin{table}[htbp]", r"\centering", r"\small",
              r"\caption{Tracking pipeline (YOLO26s + ByteTrack + cls\_v5\_img128, 3-of-8 vote with mean score "
              r"$\geq$ 0.70) on the Islamabad videos. A pass counts as detected if confirmed within 1\,s of its "
              r"hand-labelled window.}",
              r"\label{tab:it2-tracking}", r"\begin{tabular}{lcccccc}", r"\hline",
              r"Video & Crops used in & Passes & Detected & Missed & False events & Latency (s) \\", r"\hline"]
        for r in csv.DictReader(tf.open()):
            if r["processed"] != "True":
                continue
            L.append(f"{esc(r['video'])} & {r['used_for_training_crops']} & {r['ambulance_passes']} & {r['detected']} & "
                     f"{r['missed']} & {r['false_events']} & {r['latency_s'] or '--'} \\\\")
        L += [r"\hline", r"\end{tabular}", r"\end{table}", ""]

    L += classifier_tables()

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", OUT)


def classifier_tables() -> list[str]:
    """Ambulance classifier: test split, val comparison of the cls_v5 runs, vote re-tuning, GPU latency.
    Sources: ../Projects/runs/eval_test*/metrics.json (eval_detector.py), runs/<name>/val_metrics.json
    (train_cls_v5.py), tracking_out/tune/sweep.csv (tune_tracking.py)."""
    import json

    P = ROOT.parent / "Projects"
    L: list[str] = []
    pct = lambda x: f"{100 * float(x):.1f}\\%"  # noqa: E731

    # test split
    runs = [("cls\\_v4-2 (mid-report)", P / "runs" / "eval_test" / "metrics.json"),
            ("cls\\_v5\\_img128 (pipeline)", P / "runs" / "eval_test_v5_img128" / "metrics.json")]
    runs = [(n, json.loads(f.read_text())) for n, f in runs if f.exists()]
    if runs:
        L += [r"\begin{table}[htbp]", r"\centering", r"\small",
              r"\caption{Ambulance classifier on the held-out test split (Projects/eval\_detector.py, threshold 0.5; "
              r"768 ambulance and 2\,953 other-vehicle crops).}",
              r"\label{tab:it2-cls-test}", r"\begin{tabular}{lccccccc}", r"\hline",
              r"Model & Accuracy & Precision & Recall & F1 & False alarms & ROC-AUC & PR-AUC \\", r"\hline"]
        for n, m in runs:
            c = m["confusion"]  # F1 from counts: metrics.json stores it already rounded to 4 places
            f1 = 2 * c["tp"] / (2 * c["tp"] + c["fp"] + c["fn"])
            L.append(f"{n} & {pct(m['accuracy'])} & {pct(m['precision'])} & {pct(m['recall'])} & {f1:.3f} & "
                     f"{pct(m['false_alarm_rate'])} & {m['roc_auc']:.3f} & {m['pr_auc']:.3f} \\\\")
        L += [r"\hline", r"\end{tabular}", r"\end{table}", ""]

    # val comparison of the training runs
    names = [("cls_v4-2", "mid-report model"), ("cls_v5_base", "same settings, cleaned data"),
             ("cls_v5_img128", "input 128\\,px"), ("cls_v5_os2", "ambulance crops $\\times$2")]
    rows = [(n, d, json.loads((P / "runs" / n / "val_metrics.json").read_text()))
            for n, d in names if (P / "runs" / n / "val_metrics.json").exists()]
    if rows:
        L += [r"\begin{table}[htbp]", r"\centering", r"\small",
              r"\caption{Classifier training runs on the cleaned validation split (yolo26n-cls, 30 epochs; "
              r"Projects/train\_cls\_v5.py). The model was chosen here and then run once on the test split.}",
              r"\label{tab:it2-cls-val}", r"\begin{tabular}{llccccc}", r"\hline",
              r"Run & Change & PR-AUC & Recall & Precision & F1 & False alarms \\", r"\hline"]
        for n, d, m in rows:
            t = m["th0.5"]
            L.append(f"{esc(n)} & {d} & {m['pr_auc']:.3f} & {pct(t['recall'])} & {pct(t['precision'])} & "
                     f"{t['f1']:.3f} & {pct(t['false_alarm_rate'])} \\\\")
        L += [r"\hline", r"\end{tabular}", r"\end{table}", ""]

    # vote re-tuning
    sf = P / "tracking_out" / "tune" / "sweep.csv"
    if sf.exists():
        sweep = {(r["th_frame"], r["mean_min"], r["k"]): r for r in csv.DictReader(sf.open())}
        pick = [("before", ("0.6", "0.65", "5")), ("after", ("0.6", "0.7", "3"))]
        L += [r"\begin{table}[htbp]", r"\centering", r"\small",
              r"\caption{Re-tuning the confirmation vote for cls\_v5\_img128 on the 12 Islamabad videos "
              r"(Projects/tune\_tracking.py, 360 settings replayed offline; window M = 8 frames).}",
              r"\label{tab:it2-tune}", r"\begin{tabular}{lcccccc}", r"\hline",
              r"Setting & Frame threshold & Mean score & K of 8 & Passes detected & False events & Latency (s) \\",
              r"\hline"]
        for n, k in pick:
            r = sweep.get(k)
            if r:
                L.append(f"{n} & {k[0]} & {k[1]} & {k[2]} & {r['detected']} of {r['passes']} & "
                         f"{r['false_events']} & {r['mean_latency_s'] or '--'} \\\\")
        L += [r"\hline", r"\end{tabular}", r"\end{table}", ""]

    # GPU latency (eval_test: measured on mains power)
    lf = P / "runs" / "eval_test" / "metrics.json"
    if lf.exists() and "latency" in json.loads(lf.read_text()):
        lat = json.loads(lf.read_text())["latency"]
        L += [r"\begin{table}[htbp]", r"\centering", r"\small",
              r"\caption{Perception latency on an RTX 4050 laptop GPU (Projects/eval\_detector.py, a real 1280\,px "
              r"video frame).}",
              r"\label{tab:it2-latency}", r"\begin{tabular}{lccc}", r"\hline",
              r"Stage & Mean (ms) & Median (ms) & p95 (ms) \\", r"\hline"]
        for key, label in (("detector_frame", "YOLO26s vehicle detector, one frame"),
                           ("classifier_batch1", "classifier, one crop"),
                           ("classifier_batch16", "classifier, batch of 16 crops")):
            if key in lat:
                x = lat[key]
                extra = f" ({x['per_crop_ms']}\\,ms per crop)" if "per_crop_ms" in x else ""
                L.append(f"{label}{extra} & {x['mean_ms']} & {x['median_ms']} & {x['p95_ms']} \\\\")
        pe = lat.get("pipeline_estimate", {})
        if pe:
            L.append(r"\hline")
            L.append(f"full pipeline, 10 vehicles in view (estimate) & {pe.get('10_vehicles_ms', '--')} & & \\\\")
        L += [r"\hline", r"\end{tabular}", r"\end{table}", ""]
    return L


if __name__ == "__main__":
    main()
